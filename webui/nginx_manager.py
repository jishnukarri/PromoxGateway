import ipaddress
import json
import re
import subprocess
from pathlib import Path
from dotenv import load_dotenv
import os

STATE_FILE = Path("/var/lib/proxmox-gateway/state.json")
ROUTES_FILE = Path("/var/lib/proxmox-gateway/nginx_routes.json")

CONFIG_DIR = Path("/etc/nginx/proxmox-gateway")
CONFIG_FILE = CONFIG_DIR / "routes.conf"

ENV_FILE = ".env"

load_dotenv(ENV_FILE)

SSL_CERT = os.getenv("SSL_CERT")
SSL_KEY = os.getenv("SSL_KEY")

DOMAIN_RE = re.compile(
    r"^[a-zA-Z0-9]"
    r"(?:[a-zA-Z0-9.-]{0,251}"
    r"[a-zA-Z0-9])?$"
)


def load_json(path, default):
    try:
        return json.loads(path.read_text())
    except (FileNotFoundError, json.JSONDecodeError):
        return default


def validate_domain(domain):
    domain = domain.strip().lower()

    if not domain:
        raise ValueError("empty domain")

    if len(domain) > 253:
        raise ValueError("domain too long")

    if not DOMAIN_RE.fullmatch(domain):
        raise ValueError(
            f"invalid domain: {domain}"
        )

    if ".." in domain:
        raise ValueError(
            f"invalid domain: {domain}"
        )

    for label in domain.split("."):
        if (
            not label
            or len(label) > 63
            or label.startswith("-")
            or label.endswith("-")
        ):
            raise ValueError(
                f"invalid domain: {domain}"
            )

    return domain


def validate_port(value):
    port = int(value)

    if not 1 <= port <= 65535:
        raise ValueError(
            f"invalid port: {port}"
        )

    return port


def nginx_test():
    result = subprocess.run(
        ["nginx", "-t"],
        text=True,
        capture_output=True,
    )

    if result.returncode != 0:
        raise RuntimeError(
            result.stdout + result.stderr
        )


def reload_nginx():
    result = subprocess.run(
        [
            "systemctl",
            "reload",
            "nginx",
        ],
        text=True,
        capture_output=True,
    )

    if result.returncode != 0:
        raise RuntimeError(
            result.stdout + result.stderr
        )


def rebuild():
    state = load_json(
        STATE_FILE,
        {},
    )

    routes = load_json(
        ROUTES_FILE,
        [],
    )

    guests = {
        guest["name"]: guest
        for guest in state.values()
        if guest.get("ip")
    }

    active = []

    for route in routes:
        guest = guests.get(
            route.get("guest")
        )

        if not guest:
            continue

        try:
            domain = validate_domain(
                route.get("domain", "")
            )

            port = validate_port(
                route.get("port")
            )

            ipaddress.ip_address(
                guest["ip"]
            )

        except (
            ValueError,
            TypeError,
        ):
            continue

        active.append(
            {
                **route,
                "domain": domain,
                "ip": guest["ip"],
                "port": port,
            }
        )

    lines = [
        "# Managed by Proxmox Gateway.",
        "# DO NOT EDIT THIS FILE MANUALLY.",
        "",
    ]

    for route in active:
        lines.extend(
            [
                "server {",
                "    listen 80;",
                f"    server_name {route['domain']};",
                "",
                "    return 301 https://$host$request_uri;",
                "}",
                "",
                "server {",
                "    listen 443 ssl;",
                f"    server_name {route['domain']};",
                "",
                f"    ssl_certificate {SSL_CERT};",
                f"    ssl_certificate_key {SSL_KEY};",
                "",
                "    location / {",
                f"        proxy_pass http://{route['ip']}:{route['port']};",
                "",
                "        proxy_http_version 1.1;",
                "        proxy_set_header Host $host;",
                "        proxy_set_header X-Real-IP $remote_addr;",
                "        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;",
                "        proxy_set_header X-Forwarded-Proto $scheme;",
                "        proxy_set_header Upgrade $http_upgrade;",
                '        proxy_set_header Connection "upgrade";',
                "        proxy_read_timeout 3600;",
                "        proxy_send_timeout 3600;",
                "    }",
                "}",
                "",
            ]
        )

    config = "\n".join(lines)

    CONFIG_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    # Always create the file, even with zero routes.
    if not CONFIG_FILE.exists():
        CONFIG_FILE.write_text(config)
        return active

    old_config = CONFIG_FILE.read_text()

    if config == old_config:
        return active

    CONFIG_FILE.write_text(config)

    try:
        nginx_test()
        reload_nginx()

    except Exception:
        CONFIG_FILE.write_text(
            old_config
        )
        raise

    return active
